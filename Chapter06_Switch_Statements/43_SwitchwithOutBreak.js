let day=10;

switch(day){
    case 1:
        console.log("Monday");
   
    case 2:
        console.log("Tuesday");
        
    case 3:
        console.log("Wednesday");
       
    case 4:
        console.log("Thursday");
        break;
    case 5:
        console.log("Friday");
        break;
    default:
        console.log("Invalid day");
}